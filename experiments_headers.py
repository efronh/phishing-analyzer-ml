#!/usr/bin/env python3
# Gönderen doğrulaması (SPF, DKIM, DMARC) ölçümü: eğitimdeki phishing (Nazario 2019-2024) ile
# yazarın reklam mailleri. Protokol (sonuçlardan önce yazıldı): reports/HEADERS_PROTOCOL.md
# Phishing Pot ve lockbox bilerek kullanılmıyor (ileride başlık feature'larını kör test için).
# Gizlilik: reklamlar için sadece toplam oranlar; hiçbir başlık değeri ya da domain yazdırılmaz.
#
# Kullanım: python experiments_headers.py

import collections
import json
import mailbox
import os
import sys
import time

from email_parsing import parse_bytes
from evaluation import wilson_ci
from experiments_commercial import load_promo, load_redactor, promo_mbox_paths
from header_signals import MECHANISMS, SIGNAL_NAMES, header_signals

RAW = os.path.join("data", "raw")
REPORTS = "reports"
PHISH_FILES = ["nazario-%d.mbox" % y for y in range(2019, 2025)]
MIN_PHISH_RATE = 0.05
MIN_RATIO = 3.0


def log(msg):
    print("[" + time.strftime("%H:%M:%S") + "] " + msg, flush=True)


def summarize(signals):
    out = {"n": len(signals), "signals": {}, "recorded": {}}
    for s in SIGNAL_NAMES:
        vals = [x[s] for x in signals if x[s] is not None]
        k, n = sum(vals), len(vals)
        out["signals"][s] = {"k": int(k), "n": n, "rate": round(k / n, 4) if n else None, "ci": wilson_ci(int(k), n)}
    for m in MECHANISMS:
        c = collections.Counter((x["_recorded"][m] or "missing") for x in signals)
        out["recorded"][m] = {v: round(k / len(signals), 4) for v, k in c.most_common()}
    return out


def main():
    if not promo_mbox_paths():
        print("No finished .mbox export in data/raw/own_promo/", file=sys.stderr)
        return 1
    started = time.time()
    phish = []
    for name in PHISH_FILES:
        for msg in mailbox.mbox(os.path.join(RAW, name), factory=lambda fp: parse_bytes(fp.read())):
            phish.append(header_signals(msg))
    log("phishing: " + str(len(phish)))
    redactor, _ = load_redactor()
    promo_rows, counts = load_promo(redactor, require_dmarc=False, extra=header_signals)
    promo = [r["extra"] for r in promo_rows]
    log("promotions (no DMARC filter): " + json.dumps(counts))

    groups = {"Nazario 2019-24 (phishing)": summarize(phish), "promotions (legitimate)": summarize(promo)}
    verdicts = {}
    for s in SIGNAL_NAMES:
        p = groups["Nazario 2019-24 (phishing)"]["signals"][s]
        c = groups["promotions (legitimate)"]["signals"][s]
        if p["rate"] is None or c["rate"] is None:
            verdicts[s] = {"promising": False, "ratio": None}
            continue
        ratio = p["rate"] / max(c["rate"], 1.0 / max(c["n"], 1))
        verdicts[s] = {"ratio": round(ratio, 2), "promising": bool(p["rate"] >= MIN_PHISH_RATE and ratio >= MIN_RATIO)}

    # keşif (protokolde yok, sonuçtan sonra eklendi): göndereni doğrulanmış mail oranı =
    # DMARC geçiyor VE DKIM imzası From domain'iyle eşleşiyor. İki aşamalı bir tasarımın bedelini gösterir.
    def verified(x):
        return x["dmarc_not_pass"] is False and not x["dkim_not_aligned"]

    exploratory = {}
    for name, sigs in [("Nazario 2019-24 (phishing)", phish), ("promotions (legitimate)", promo)]:
        k = sum(1 for x in sigs if verified(x))
        exploratory[name] = {"k": k, "n": len(sigs), "rate": round(k / len(sigs), 4), "ci": wilson_ci(k, len(sigs))}

    results = {"promo_counts": counts, "groups": groups, "verdicts": verdicts,
               "verified_sender_exploratory": exploratory,
               "runtime_seconds": round(time.time() - started, 1)}
    f = open(os.path.join(REPORTS, "headers.json"), "w", encoding="utf-8")
    json.dump(results, f, indent=2)
    f.close()
    write_markdown(results)
    log("Done -> reports/HEADERS.md")
    return 0


def pct(x):
    if x["rate"] is None:
        return "-"
    return "%.1f%% (%.1f–%.1f)" % (100 * x["rate"], 100 * x["ci"][0], 100 * x["ci"][1])


def write_markdown(r):
    g = r["groups"]
    P, C = g["Nazario 2019-24 (phishing)"], g["promotions (legitimate)"]
    L = ["# Sender authentication: SPF, DKIM, DMARC", ""]
    L.append("Generated by `experiments_headers.py`. Protocol, written before the first run: "
             "[`HEADERS_PROTOCOL.md`](HEADERS_PROTOCOL.md). Measurement only; nothing is added to the model.")
    L.append("")
    L.append("- **Phishing:** %d Nazario emails from 2019–2024 (training corpus). Phishing Pot and the lockbox "
             "are kept back for a later blind test." % P["n"])
    L.append("- **Legitimate:** %d of the author's promotional emails, **without** the DMARC part of the junk "
             "filter (%d sender domains, at most 30 each). They are private; this report holds rates only."
             % (C["n"], r["promo_counts"]["senders"]))
    L.append("")
    L.append("## Signals")
    L.append("")
    L.append("A signal is **promising** if it fires on at least %d%% of phishing and at least %g× as often as on "
             "promotions (rule fixed in advance). The `*_not_pass` rows count only emails with a recorded result; "
             "the denominator is shown." % (int(100 * MIN_PHISH_RATE), MIN_RATIO))
    L.append("")
    L.append("| signal | phishing | n | promotions | n | phishing ÷ promotions | promising |")
    L.append("|---|---:|---:|---:|---:|---:|---|")
    for s in SIGNAL_NAMES:
        v = r["verdicts"][s]
        L.append("| `%s` | %s | %d | %s | %d | %s | %s |" % (
            s, pct(P["signals"][s]), P["signals"][s]["n"], pct(C["signals"][s]), C["signals"][s]["n"],
            "-" if v["ratio"] is None else "%.1f×" % v["ratio"], "**yes**" if v["promising"] else "no"))
    L.append("")
    L.append("## Recorded results (share of all emails)")
    L.append("")
    L.append("From the top-most `Authentication-Results` header that reports each mechanism. Different receiving "
             "servers wrote them: iCloud for the promotions, the collector's server or a forwarder for Nazario.")
    L.append("")
    for m in MECHANISMS:
        values = sorted(set(P["recorded"][m]) | set(C["recorded"][m]),
                        key=lambda v: -(P["recorded"][m].get(v, 0) + C["recorded"][m].get(v, 0)))
        L.append("**" + m.upper() + "**")
        L.append("")
        L.append("| result | phishing | promotions |")
        L.append("|---|---:|---:|")
        for v in values:
            L.append("| %s | %.1f%% | %.1f%% |" % (v, 100 * P["recorded"][m].get(v, 0), 100 * C["recorded"][m].get(v, 0)))
        L.append("")
    ex = r.get("verified_sender_exploratory")
    if ex:
        L.append("## Verified sender (exploratory, added after the result)")
        L.append("")
        L.append("Not in the protocol. A **verified sender** passes DMARC and carries a DKIM signature aligned with "
                 "its `From` domain: the mail really comes from the domain it shows. That does not make the domain "
                 "honest; phishers can authenticate their own lookalike domains.")
        L.append("")
        L.append("| group | verified sender |")
        L.append("|---|---:|")
        for name, x in ex.items():
            L.append("| %s | %s |" % (name, pct(x)))
        L.append("")
    L.append("## Caveats")
    L.append("")
    L.append("- **No mailing-list baseline:** the archives strip these headers, so the only legitimate comparison is "
             "one inbox of promotions.")
    L.append("- **`from_freemail` looks stronger than it is:** real legitimate mail includes person-to-person mail "
             "from freemail addresses, which a promotions-only set lacks.")
    L.append("- **Forwarding:** many Nazario messages carry ARC headers, a sign of forwarding, which can break SPF "
             "and DMARC. The computed checks (`dkim_not_aligned`, `return_path_not_aligned`, `reply_to_other_domain`) "
             "do not depend on the receiver.")
    L.append("")
    f = open(os.path.join(REPORTS, "HEADERS.md"), "w", encoding="utf-8")
    f.write("\n".join(L))
    f.close()


if __name__ == "__main__":
    sys.exit(main())
